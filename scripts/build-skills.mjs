#!/usr/bin/env node
// Builds skills/<name>/SKILL.md from .claude/commands/<name>.md.
// The commands stay canonical; skills are generated so hosts that only import
// skills (plugin marketplaces, Claude Science) see the same prompts.
// Usage: node scripts/build-skills.mjs [--check]   (--check writes nothing, exits 1 on drift)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Frontmatter descriptions. Command files start with a template-version comment, so
// they carry no frontmatter of their own; this table is the single source for it.
export const DESCRIPTIONS = Object.freeze({
  'experiment-adopt': 'Audit an existing research or computational project and write advisory adoption documentation (artifact classification, documentation gaps, onboarding roadmap) before starting the experiment lifecycle. Use when taking over or onboarding a mid-stream project. Arguments: [project_path] [--workstream name] [--deep] [--git-history N] [--output path].',
  'experiment-init': 'Scaffold the experiment documentation lifecycle for a computational science project, adding missing files at the resolved research, code and work locations without overwriting existing ones. Use when starting a new project. Arguments: <project_name> [--description "text"] [--domain "tags"] [--minimal] [--locations path] [--project-file path].',
  'experiment-plan': 'Define objectives, phases, expected outputs and success criteria for a workstream and write the plan document. Use before executing an analysis. Arguments: [workstream] [--output path] [--phases N].',
  'experiment-capture': 'Record a process artifact from the current session: commands, scripts, data lineage, measurements, decisions and issues. Use after a phase of analysis work. Arguments: [workstream] [qualifier] [--plan path] [--output path].',
  'experiment-findings': 'Synthesize result files, process artifacts and plan success criteria into a findings document for a workstream phase. Use once results exist. Arguments: [workstream] [scope] [--plan path] [--process path] [--results path] [--output path].',
  'experiment-report': 'Compile an IMRAD-style report integrating all findings for a workstream; --oligon requests the branded PDF. Use when the findings for a workstream are complete. Arguments: [workstream] [--output path] [--oligon] [--scope "phase1,phase2"] [--title "Custom Title"].',
});

const BASE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Pure function: command text in, SKILL.md text out. The body is passed through unchanged,
// so every pinned protocol block in the command is byte-identical in its skill.
export function render(name, commandText) {
  const description = DESCRIPTIONS[name];
  if (!description) throw new Error(`No description registered for ${name}`);
  return [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`, // JSON string quoting is valid YAML
    '---',
    `<!-- Generated by scripts/build-skills.mjs from .claude/commands/${name}.md. Edit the command, then re-run the script. -->`,
    commandText,
  ].join('\n');
}

export function build({ base = BASE, check = false } = {}) {
  const drift = [];
  for (const name of Object.keys(DESCRIPTIONS)) {
    const source = fs.readFileSync(path.join(base, '.claude/commands', `${name}.md`), 'utf8');
    const target = path.join(base, 'skills', name, 'SKILL.md');
    const expected = render(name, source);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (current === expected) continue;
    drift.push(name);
    if (!check) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, expected);
    }
  }
  return drift;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const drift = build({ check });
  if (check && drift.length) {
    console.error(`skills out of date: ${drift.join(', ')} (run node scripts/build-skills.mjs)`);
    process.exit(1);
  }
  console.log(drift.length ? `${check ? 'drift' : 'wrote'}: ${drift.join(', ')}` : 'skills up to date');
}
